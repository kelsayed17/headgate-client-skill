"""Write the skill's ``references/verifier.md`` from the rules and checks ``headgate-verify`` runs.

The rule list is read from the verifier itself: every YAML rule (``load_rules()``: id, severity, message, and the
``Config`` fields it reads) and every Python check (``CHECKS``: id, severity from ``WARNING_CHECKS``, and the first
sentence its module docstring gives after the check's id). Run it after changing a rule; ``--check`` exits 1, writing
nothing, when the file is not what it would write (CI and ``tests/test_repo.py`` run that).

    uv run python scripts/gen_rule_docs.py           # rewrite the file
    uv run python scripts/gen_rule_docs.py --check   # exit 1 if it is stale
"""

import argparse
import re
import sys
from dataclasses import dataclass, fields
from pathlib import Path
from typing import TYPE_CHECKING

from headgate_verify.checks import CHECKS, WARNING_CHECKS
from headgate_verify.config import Config
from headgate_verify.rules import BAD_EXEMPTION, PARSE_ERROR, YamlRule, load_rules

if TYPE_CHECKING:
    from collections.abc import Sequence

OUTPUT = Path(__file__).parent.parent / "skills" / "building-headgate-clients" / "references" / "verifier.md"
_PLACEHOLDER = re.compile(r"\{\{config\.(\w+)\}\}")
_SPACE = re.compile(r"\s+")


@dataclass(frozen=True)
class Row:
    """One rule as the reference lists it."""

    id: str
    severity: str
    message: str
    config: tuple[str, ...]


def _key(field_name: str) -> str:
    return field_name.replace("_", "-")


def _check_message(rule_id: str, module_name: str) -> str:
    """Return the first sentence the check's module docstring writes after ````<rule_id>``:``."""
    doc = sys.modules[module_name].__doc__ or ""
    match = re.search(rf"``{re.escape(rule_id)}``: (.+?\.)(?:\s|$)", doc, re.DOTALL)
    if match is None:
        msg = f"{module_name}'s docstring does not describe {rule_id} as ``{rule_id}``: <sentence>."
        raise ValueError(msg)
    return _SPACE.sub(" ", match.group(1)).replace("``", "`")


def _config_fields(rule: YamlRule) -> tuple[str, ...]:
    """Return the ``Config`` fields a YAML rule reads: its placeholders and its ``skip-packages-in`` field."""
    names: set[str] = {str(name) for name in _PLACEHOLDER.findall(rule.source)}
    if rule.skip_packages_in is not None:
        names.add(rule.skip_packages_in)
    return tuple(sorted(names))


def rows() -> list[Row]:
    """Return every YAML rule and Python check, sorted by id."""
    found = [Row(rule.id, rule.severity, rule.message, _config_fields(rule)) for rule in load_rules()]
    found += [
        Row(name, "warning" if name in WARNING_CHECKS else "error", _check_message(name, check.__module__), ())
        for name, check in CHECKS
    ]
    return sorted(found, key=lambda row: row.id)


def _cell(text: str) -> str:
    return text.replace("|", "\\|")


def _config_rows() -> list[str]:
    readers: dict[str, list[str]] = {}
    for row in rows():
        for field_name in row.config:
            readers.setdefault(field_name, []).append(f"`{row.id}`")
    lines = []
    for field in fields(Config):
        default = ", ".join(f'"{value}"' for value in sorted(getattr(Config(), field.name)))
        used = ", ".join(readers.get(field.name, [])) or "no rule; pass it to `check_names` yourself"
        lines.append(f"| `{_key(field.name)}` | `[{default}]` | {used} |")
    return lines


_HEAD = """\
# The verifier

<!-- Generated by scripts/gen_rule_docs.py from the rules and checks headgate-verify runs. Do not edit by hand. -->

`headgate-verify` reads a client package's source with ast-grep-py. It never imports the code and never touches the
network.

## Running it

```bash
uv run headgate-verify path/to/provider          # one client package
uv run headgate-verify src/                      # every client package under a directory
uv run headgate-verify --format json src/        # findings as a JSON list, for an agent or CI
```

A *client package* is a directory holding a `client.py`; every directory under the given paths that holds one is
checked, except directories named `tests` or `.venv` or starting with `.`. Each finding is one line,
`<file>:<line> <rule-id> <message>`; with `--format json` each is an object with `rule`, `path`, `line`, `message` and
`severity`.

| Exit | Meaning |
|---|---|
| `0` | no error (warnings may have been printed) |
| `1` | at least one error |
| `2` | a usage error: no path given, a path that does not exist, or a malformed `[tool.headgate-verify]` table |

## Configuration

The verifier reads `[tool.headgate-verify]` from the `pyproject.toml` nearest the **current working directory** (at
or above it), not the one nearest the checked package, so run it from the project root. Every key is a list of
strings; an unknown key, or a value that is not a list of strings, is exit `2`.

```toml
[tool.headgate-verify]
browser-user-agent-packages = ["scraped_portal"]   # packages whose host forces a browser User-Agent
write-name-fragments = ["order", "orders", "transfer", "withdraw", "payment"]
```

| Key | Default | Read by |
|---|---|---|
"""

_MIDDLE = """
`one-flavour` reads a different file: the `pyproject.toml` nearest the checked **package**, for the headgate extra
its flavour needs.

## Allow comments

A finding a reader has judged acceptable is exempted by a comment naming its rule and the reason:

```python
async def download(self, report_id: str) -> bytes:  # headgate-verify: allow client-method-shape -- a streamed body
```

The comment covers a finding on its own line, or anywhere inside the `def` or `class` whose first line carries it. A
finding against a whole module (reported at line 1) is also covered by a comment above the module's first statement,
below a licence header. An allow comment with no reason after `--`, naming an unknown rule, or suppressing nothing is
itself an error, `bad-exemption`.

## The rules

Errors fail the run; warnings never do, but the skill requires each one resolved in writing before a client is done
(an allow comment carrying the reason). The message is the rule's own; a Python check's findings each say what they
found, and the line here is the check's summary.

| Rule | Severity | Message |
|---|---|---|
"""

_TAIL = f"""
Two findings come from the verifier itself, not a rule:

| Finding | Severity | Meaning |
|---|---|---|
| `{BAD_EXEMPTION}` | error | an allow comment is malformed, has no reason, names no known rule, or drops nothing |
| `{PARSE_ERROR}` | error | a module does not parse (Python's own parser, then tree-sitter's); no rule read it |

## What it does not check

- Method names against the docs. That is `headgate_verify.naming.check_names`, which each package's
  `test_method_names.py` runs under pytest (see [naming.md](naming.md)). The verifier checks only that the test file
  and `docs_paths.json` exist and that the snapshot follows its schema. A doc-heading method name passes the verifier
  and fails the naming test.
- Whether the client works. Its tests (see [testing.md](testing.md)) do that.
"""


def render() -> str:
    """Return the text of ``references/verifier.md``."""
    table = [f"| `{row.id}` | {row.severity} | {_cell(row.message)} |" for row in rows()]
    return _HEAD + "\n".join(_config_rows()) + "\n" + _MIDDLE + "\n".join(table) + "\n" + _TAIL


def main(argv: Sequence[str] | None = None) -> int:
    """Write the reference, or with ``--check`` return 1 when it differs from what would be written."""
    parser = argparse.ArgumentParser(description="Write references/verifier.md from the verifier's rules.")
    parser.add_argument("--check", action="store_true", help="exit 1 if the file is stale; write nothing")
    parser.add_argument("--output", type=Path, default=OUTPUT, help="the file to write or check")
    args = parser.parse_args(argv)
    text = render()
    current = args.output.read_text(encoding="utf-8") if args.output.is_file() else None
    if args.check:
        if current != text:
            sys.stderr.write(f"{args.output} is stale; run: uv run python scripts/gen_rule_docs.py\n")
            return 1
        return 0
    if current != text:
        args.output.write_text(text, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
