"""Write the skill's ``references/verifier.md`` from the rules and checks ``headgate-verify`` runs.

The rule list is read from the verifier itself: every YAML rule (``load_rules()``: id, severity, message, the
``Config`` fields it reads, and its ``note`` as the fix) and every Python check (``CHECKS``: its ``RULE``'s id,
severity and fix, and the first sentence its module docstring gives after the check's id).
Run it after changing a rule; ``--check`` exits 1, writing nothing, when the file is not what it would write (CI and
``tests/test_repo.py`` run that).

    uv run python scripts/gen_rule_docs.py           # rewrite the file
    uv run python scripts/gen_rule_docs.py --check   # exit 1 if it is stale
"""

import argparse
import re
import sys
from dataclasses import dataclass, fields
from pathlib import Path
from typing import TYPE_CHECKING

from headgate_verify.checks import CHECKS
from headgate_verify.config import Config
from headgate_verify.exemptions import BAD_EXEMPTION
from headgate_verify.parsing import PARSE_ERROR
from headgate_verify.rules import RESERVED, load_rules

if TYPE_CHECKING:
    from collections.abc import Sequence

OUTPUT = Path(__file__).parent.parent / "skills" / "building-headgate-clients" / "references" / "verifier.md"
_SPACE = re.compile(r"\s+")
_NAMING_FIELDS = frozenset({"filler_words", "post_reads"})
"""The ``Config`` fields ``check_names`` defaults from the package's pyproject (ruling R26); no YAML rule reads them."""
_NAMING_READER = "`check_names`, in the naming test"
_ENGINE_FIELDS = frozenset({"rule_dirs"})
"""The ``Config`` fields the engine itself reads; no rule reads them."""
_ENGINE_READER = "the command: the project's own rules, run beside these"


@dataclass(frozen=True)
class Row:
    """One rule as the reference lists it."""

    id: str
    severity: str
    message: str
    config: tuple[str, ...]
    fix: str


def _key(field_name: str) -> str:
    return field_name.replace("_", "-")


def _check_message(rule_id: str, module_name: str) -> str:
    """Return the first sentence the check's module docstring writes after ````<rule_id>``:``."""
    doc = sys.modules[module_name].__doc__ or ""
    match = re.search(rf"``{re.escape(rule_id)}``: (.+?\.)(?:\s|$)", doc, re.DOTALL)
    if match is None:
        msg = f"{module_name}'s docstring does not describe {rule_id} as ``{rule_id}``: <sentence>."
        raise ValueError(msg)
    return _SPACE.sub(" ", match.group(1)).replace("``", "`")


def rows() -> list[Row]:
    """Return every YAML rule and Python check, sorted by id."""
    found = [Row(rule.id, rule.severity, rule.message, rule.config_fields, rule.fix) for rule in load_rules()]
    found += [
        Row(check.rule.id, check.rule.severity, _check_message(check.rule.id, check.run.__module__), (), check.rule.fix)
        for check in CHECKS
    ]
    return sorted(found, key=lambda row: row.id)


def _cell(text: str) -> str:
    return text.replace("|", "\\|")


def _config_rows() -> list[str]:
    readers: dict[str, list[str]] = {}
    for row in rows():
        for field_name in row.config:
            readers.setdefault(field_name, []).append(f"`{row.id}`")
    lines = []
    for field in fields(Config):
        default = ", ".join(f'"{value}"' for value in sorted(getattr(Config(), field.name)))
        own = []
        if field.name in _NAMING_FIELDS:
            own.append(_NAMING_READER)
        if field.name in _ENGINE_FIELDS:
            own.append(_ENGINE_READER)
        used = ", ".join([*readers.get(field.name, []), *own])
        lines.append(f"| `{_key(field.name)}` | `[{default}]` | {used} |")
    return lines


_HEAD = """\
# The verifier

<!-- Generated by scripts/gen_rule_docs.py from the rules and checks headgate-verify runs. Do not edit by hand. -->

`headgate-verify` reads a client package's source with ast-grep-py. It never imports the code and never touches the
network.

## Running it

```bash
uv run headgate-verify path/to/provider          # one client package
uv run headgate-verify src/                      # every client package under a directory
uv run headgate-verify --format json src/        # findings as a JSON list, for an agent or CI
```

A *client package* is a directory holding a `client.py`; every directory under the given paths that holds one is
checked, except directories named `tests`, `.venv`, `venv`, `build`, `dist`, `node_modules` or `site-packages`, or
starting with `.`. Each finding is one line on stdout, `<file>:<line> <severity> <rule-id> <message>`, followed by
its fix indented by four spaces; with `--format json` each is an object with `rule`, `path`, `line`, `message`,
`severity` and `fix`. stdout carries nothing else: after a run, stderr says `checked N package(s)`.

| Exit | Meaning |
|---|---|
| `0` | no error (warnings may have been printed) |
| `1` | at least one error |
| `2` | a usage error: no path, a missing path, a path with no client package, a bad config table or project rule |

A run that checks nothing is not clean: every path under which no client package is found is named on stderr, and
the exit is `2`.

## Configuration

Two readers take `[tool.headgate-verify]` from two places. The `headgate-verify` command reads the `pyproject.toml`
nearest the **current working directory** (at or above it), not the one nearest the checked package, so run it from
the project root. The naming test's `check_names` reads the `pyproject.toml` nearest the **package's `client.py`**,
for `filler-words` and `post-reads`, unless the test passes `filler=` or `post_reads=` itself (see
[naming.md](naming.md)). Every key is a list of strings; an unknown key, or a value that is not a list of strings, is
exit `2` for the command and a `ConfigError` for `check_names`.

```toml
[tool.headgate-verify]
browser-user-agent-packages = ["scraped_portal"]   # packages whose host forces a browser User-Agent
post-reads = ["search_orders"]                     # reads by POST: named like reads, never held to retry=
write-name-fragments = ["order", "redeem"]         # REPLACES the defaults (the table below): list every fragment
```

| Key | Default | Read by |
|---|---|---|
"""

_MIDDLE = """
`rule-dirs` entries are directories relative to that `pyproject.toml`. Each `<id>.yml` in them is a rule in the
same format as the shipped ones, run beside them, with its `note` as the fix and allow comments naming its id. A
project rule may not take the id of a shipped rule, a check or a reserved id. A directory that does not exist, a
file that is not valid YAML, a rule ast-grep refuses, a `.yaml` file (rules are `.yml`) or a taken id is exit `2`,
before any package is read. Rules are read on every run. Test a project rule as the shipped ones are tested: a
package per case, checked with `headgate_verify.engine.verify(paths, load_config(root))`.

`one-flavour` reads a different file: the `pyproject.toml` nearest the checked **package**, for the headgate extra
its flavour needs.

## Allow comments

A finding a reader has judged acceptable is exempted by a comment naming its rule and the reason:

```python
async def download(self, report_id: str) -> bytes:  # headgate-verify: allow client-method-shape -- a streamed body
```

The comment covers a finding on its own line, or anywhere inside the `def` or `class` whose first line carries it. A
finding against a whole module (reported at line 1) is also covered by a comment above the module's first statement,
below a licence header. An allow comment with no reason after `--`, naming an unknown rule, or suppressing nothing is
itself an error, `bad-exemption`.

## The rules

Errors fail the run; warnings never do, but the skill requires each one resolved in writing before a client is done
(an allow comment carrying the reason). The message is the rule's own; a Python check's findings each say what they
found, and the line here is the check's summary.

| Rule | Severity | Message |
|---|---|---|
"""

_RESERVED_MEANINGS = {
    BAD_EXEMPTION.id: "an allow comment is malformed, has no reason, names no known rule, or drops nothing",
    PARSE_ERROR.id: "a module cannot be read or parsed (Python's parser, then tree-sitter's); no rule read it",
}
"""What each finding the engine itself reports means, by id."""

_TAIL = """
Two findings come from the verifier itself, not a rule:

| Finding | Severity | Meaning |
|---|---|---|
{RESERVED}

## How to fix each rule

Every finding carries its rule's fix: the YAML rule's `note`, or the check's registered sentence. The text format
prints it under the finding; `--format json` gives it as `fix`.

| Rule | How to fix |
|---|---|
{FIXES}

## What it does not check

- Method names against the docs. That is `headgate_verify.naming.check_names`, which each package's
  `test_method_names.py` runs under pytest (see [naming.md](naming.md)). The verifier checks only that the test file
  and `docs_paths.json` exist and that the snapshot follows its schema. A doc-heading method name passes the verifier
  and fails the naming test.
- Whether the client works. Its tests (see [testing.md](testing.md)) do that.
"""


def render() -> str:
    """Return the text of ``references/verifier.md``."""
    table = [f"| `{row.id}` | {row.severity} | {_cell(row.message)} |" for row in rows()]
    fixes = [f"| `{row.id}` | {_cell(row.fix)} |" for row in rows()]
    fixes += [f"| `{rule.id}` | {_cell(rule.fix)} |" for rule in sorted(RESERVED, key=lambda rule: rule.id)]
    reserved = [f"| `{rule.id}` | {rule.severity} | {_RESERVED_MEANINGS[rule.id]} |" for rule in RESERVED]
    tail = _TAIL.replace("{RESERVED}", "\n".join(reserved)).replace("{FIXES}", "\n".join(fixes))
    return _HEAD + "\n".join(_config_rows()) + "\n" + _MIDDLE + "\n".join(table) + "\n" + tail


def main(argv: Sequence[str] | None = None) -> int:
    """Write the reference, or with ``--check`` return 1 when it differs from what would be written."""
    parser = argparse.ArgumentParser(description="Write references/verifier.md from the verifier's rules.")
    parser.add_argument("--check", action="store_true", help="exit 1 if the file is stale; write nothing")
    parser.add_argument("--output", type=Path, default=OUTPUT, help="the file to write or check")
    args = parser.parse_args(argv)
    text = render()
    current = args.output.read_text(encoding="utf-8") if args.output.is_file() else None
    if args.check:
        if current != text:
            sys.stderr.write(f"{args.output} is stale; run: uv run python scripts/gen_rule_docs.py\n")
            return 1
        return 0
    if current != text:
        args.output.write_text(text, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
